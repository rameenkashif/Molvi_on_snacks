"""Turn results/*.json into LaTeX tables for the IEEE report (docs/report/tables.tex) and draw
the stamped instance map. Run by run_all.py after all experiments."""
from __future__ import annotations
import json, os, sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from src.world import load_world, STAMP  # noqa: E402
from experiments.common import save_fig, plt, OUT  # noqa: E402
from matplotlib.colors import ListedColormap  # noqa: E402

TEX = os.path.join(ROOT, "docs", "report", "tables.tex")


def esc(x) -> str:
    s = str(x)
    for a, b in (("\\", "/"), ("&", "\\&"), ("%", "\\%"), ("_", "\\_"), ("#", "\\#"),
                 ("±", "$\\pm$"), ("*", "$^*$"), (">", "$>$"), ("<", "$<$")):
        s = s.replace(a, b)
    return s


def table(rows, cols, caption, label, headers=None, size="\\footnotesize") -> str:
    headers = headers or cols
    out = ["\\begin{table}[t]", "\\centering", size, f"\\caption{{{caption}}}", f"\\label{{{label}}}",
           "\\setlength{\\tabcolsep}{3pt}",
           "\\begin{tabular}{" + "l" * 1 + "r" * (len(cols) - 1) + "}", "\\toprule",
           " & ".join(esc(h) for h in headers) + " \\\\", "\\midrule"]
    for r in rows:
        out.append(" & ".join(esc(r.get(c, "")) for c in cols) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(out)


def load(name):
    p = os.path.join(OUT, name)
    return json.load(open(p)) if os.path.exists(p) else None


def instance_map():
    w = load_world()
    cmap = ListedColormap(["#f2f2f2", "#b7dd9a", "#b48a5a", "#4f8fd6", "#333333"])
    fig, ax = plt.subplots(figsize=(6.5, 6.8))
    ax.imshow(np.where(w.grid < 0, 4, w.grid), cmap=cmap, vmin=0, vmax=4)
    for a, b in {tuple(sorted(x)) for x in w.tunnels.items()}:
        ax.plot([a[1], b[1]], [a[0], b[0]], ":", c="purple")
        for m in (a, b):
            ax.scatter(m[1], m[0], s=80, facecolors="none", edgecolors="purple", lw=2)
    for i, s in enumerate(w.stops):
        ax.scatter(s[1], s[0], marker="*", s=300, c="gold", edgecolors="k", zorder=5)
        ax.text(s[1] + .4, s[0] - .4, f"S{i + 1}", weight="bold")
    ax.scatter(w.start[1], w.start[0], marker="s", s=120, c="white", edgecolors="k", zorder=5)
    ax.text(w.start[1] + .4, w.start[0] - .4, "depot")
    ax.scatter(w.rival_start[1], w.rival_start[0], marker="X", s=140, c="#c62828", zorder=5)
    ax.set_title(f"Instance {w.inst['instance_id']}: road / grass / mud / ford (blue) / blocked;\n"
                 "purple = tunnel pairs, X = default rival start", fontsize=9)
    save_fig(fig, "instance_map.png")


def main():
    print(STAMP)
    instance_map()
    parts = [f"% generated by experiments/make_report_tables.py -- {STAMP}", ""]
    b = load("part_b_search.json")
    if b:
        rows = [r for r in b["algorithms_one_stop"] if r["problem"] == "depot->S4"] + b["algorithms_full"]
        parts.append(table(rows, ["problem", "algorithm", "cost", "steps", "expanded", "max_stored", "peak_mem_kb", "time_ms"],
                           "Search algorithms (1-stop variant and full tour).", "tab:alg",
                           ["problem", "alg.", "cost", "steps", "expanded", "stored", "mem KB", "ms"]))
        rows = [r for r in b["heuristics"] if r["flood_left"] == 0]
        parts.append(table(rows, ["heuristic", "h(start)", "A* cost", "A* expanded", "A* ms", "consistency viol.", "Greedy cost"],
                           "Heuristics with A* on the full tour (optimal cost 111).", "tab:heur",
                           ["heuristic", "h(s0)", "cost", "expanded", "ms", "viol.", "Greedy"]))
        parts.append(table(b["admissibility"], list(b["admissibility"][0]),
                           "Admissibility on 150 sampled states (h* from UCS).", "tab:adm"))
        parts.append(table(b["inadmissible"], list(b["inadmissible"][0]),
                           "Inadmissible / faster variants and their cost gap.", "tab:inadm"))
        rows = [r for r in b["memory_limit"] if r["problem"] == "depot->S4"]
        parts.append(table(rows, ["node cap", "A* ok", "A* stored", "IDS ok", "IDS stored", "IDS expanded", "IDS ms"],
                           "Memory limit (stored-node cap), depot to S4.", "tab:mem"))
    c = load("part_c_rival.json")
    if c:
        parts.append(table(c["node_counts"], ["depth", "root", "minimax", "AB (no order)", "AB (our order)",
                                              "saved % (no order)", "saved % (our order)"],
                           "Nodes per decision, Minimax vs Alpha-Beta.", "tab:nodes",
                           ["d", "root", "MM", "AB", "AB+ord", "saved", "saved+ord"]))
        parts.append(table(c["tuning"][:6], list(c["tuning"][0]),
                           "Weight grid search (top 6 of 18).", "tab:tune"))
        parts.append(table(c["games_summary"], ["config", "win", "draw", "loss", "delivered", "stolen"],
                           "30 games vs the blocker (Wilson 95\\% CI).", "tab:games"))
        parts.append(table(c["slip"], list(c["slip"][0]),
                           f"Slip and replanning (planner, no rival; deterministic plan {c['deterministic_plan_cost']:g}).",
                           "tab:slip"))
    d = load("part_d_llm.json")
    if d:
        parts.append(table(d["summary"], list(d["summary"][0]),
                           f"Dispatcher success over 20 requests ({esc(d['model'])}).", "tab:llm"))
    e = load("part_e_scenarios.json")
    if e:
        parts.append(table(e["configs"], ["config", "win rate", "delivered", "stolen", "cost", "replans"],
                           "30 scenarios per configuration (mean $\\pm$ 95\\% CI).", "tab:configs"))
        parts.append(table(e["flood_sweep"], ["config", "win rate", "delivered", "stolen", "cost", "dam used"],
                           "Flood duration sweep.", "tab:flood"))
        parts.append(table(e["ablation"], list(e["ablation"][0]),
                           "Heuristic ablation on 30 random stop sets.", "tab:abl"))
    os.makedirs(os.path.dirname(TEX), exist_ok=True)
    with open(TEX, "w") as f:
        f.write("\n".join(parts))
    print(f"wrote {TEX}")


if __name__ == "__main__":
    main()
